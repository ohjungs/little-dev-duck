// 2026-07-29 : 보안 - 민감 정보 자동 감지 (Phase 58 T5 U-016)
//
// 판정은 결정적 — 정규식(HD-003). **좁게만 잡는다**: 과하게 잡으면 정상 메시지마다
// 경고가 붙어 경고 자체가 무시된다(Phase 37이 오류 문구에서 내린 그 판단).
// **경고만 하고 막지 않는 것**은 호출부 계약이다 — 전송을 막으면 정상 메시지가 막힌다.
// 전화번호(3-4-4)·날짜·짧은 숫자는 일부러 안 잡는다 — 일상 대화다.

const PATTERNS: { label: string; re: RegExp }[] = [
  // 주민등록번호: 생년 6자리 - 성별 첫 자리(1-4) + 6자리. 앞뒤가 숫자면 다른 수열의 일부다.
  { label: "주민등록번호로 보이는 숫자", re: /(?<!\d)\d{6}-[1-4]\d{6}(?!\d)/ },
  // 카드번호: 4-4-4-4 (하이픈 또는 공백 구분). 구분자 없는 16자리는 오탐이 많아 안 잡는다.
  { label: "카드번호로 보이는 숫자", re: /(?<!\d)\d{4}([- ])\d{4}\1\d{4}\1\d{4}(?!\d)/ },
  // 흔한 API 키 접두사 — 접두사+길이 조건으로 좁게.
  { label: "API 키로 보이는 문자열", re: /\b(?:sk-[A-Za-z0-9_-]{20,}|ghp_[A-Za-z0-9]{36}|AKIA[0-9A-Z]{16})/ },
  // JWT: eyJ로 시작하는 3분절, 각 분절이 충분히 길 때만(짧은 언급은 안 잡는다).
  { label: "토큰(JWT)으로 보이는 문자열", re: /\beyJ[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{20,}/ },
];

/** 본문에서 민감해 보이는 것의 **종류 라벨** 목록(중복 없음, 패턴 정의 순서). 값 자체는 돌려주지 않는다 — 감지 결과가 또 하나의 유출 경로가 되면 안 된다. */
export function detectSensitiveInfo(body: string): string[] {
  if (body === "") return [];
  return PATTERNS.filter((p) => p.re.test(body)).map((p) => p.label);
}
