-- 2026-07-31 : 뉴스 - 기사 대표 이미지 컬럼 (사용자 결정 B-6)
--
-- 브리핑 카드에 대표 이미지를 넣으려면 피드의 enclosure·media:content에서 뽑은 URL을
-- 둘 자리가 필요하다. PENDING 12번이 "DDL이라 승인 대기"로 멈춰 있던 항목이고,
-- 사용자가 "기사에서 가져오든지 생성형으로 만들든지"로 진행을 결정했다.
--
-- **nullable이다.** 이미지가 없는 피드가 훨씬 많고(대부분의 개발 블로그 RSS), 없으면
-- 카드는 지금처럼 글자만 나온다. 기능 손실 0.
--
-- **길이 제한을 두지 않는다.** 추적 파라미터가 붙은 CDN URL은 쉽게 500자를 넘고, 잘라 저장하면
-- 깨진 이미지가 된다. text는 Postgres에서 varchar(n)보다 느리지 않다.
--
-- 값 검증은 코어 `safeImageUrl`이 **저장 전에** 한다(https만 통과). DB에 체크 제약을 겹치지
-- 않는 이유: 스킴 화이트리스트가 바뀔 때 마이그레이션을 또 써야 하고, 실제 방어선은
-- 이미 한 곳(코어)에 있다 — 두 벌이 되면 갈린다.
alter table public.articles add column if not exists image_url text;
