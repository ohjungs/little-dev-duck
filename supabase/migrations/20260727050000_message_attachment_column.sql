-- 이미지 버킷(20260727040000)은 만들었는데 **메시지가 그 파일을 가리킬 자리가 없었다.**
-- 계획은 별도 `attachments` 테이블을 뒀지만, 지금 필요한 건 **메시지 하나에 이미지 하나**다.
-- 테이블을 따로 두면 조인이 하나 더 붙고 목록 조회가 느려진다 — 여러 장을 붙이는 요구가
-- 실제로 생기면 그때 테이블로 옮긴다(옮기는 마이그레이션은 이 컬럼을 읽어 채우면 된다).
--
-- 20260727030000을 고치지 않고 새 파일로 둔다: 그 파일이 이미 적용됐을 가능성을
-- 우리가 확신할 수 없다. **적용된 마이그레이션을 수정하면 그 변경은 영영 반영되지 않는다.**
--
-- 경로 규약은 '<room_id>/<uuid>.<ext>'이고, 그 규약이 곧 버킷 정책의 판정 기준이다.
alter table public.messages
  add column attachment_path text
  check (attachment_path is null or char_length(attachment_path) between 1 and 300);

-- 본문 not null 제약은 그대로다. 이미지만 보내는 경우에도 **무엇이 왔는지 말하는 한 줄**이
-- 남아야 알림·목록 미리보기가 빈칸이 되지 않는다(화면이 "사진"을 넣어 보낸다).
